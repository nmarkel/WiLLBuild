#!/usr/bin/env node
// Export the registered web-GLB shells as PLAIN float32 GLBs for the
// geometry-service (Phase 0.17: shell-accurate IFC).
//
//   node scripts/web-glb/export-service-shells.mjs
//
// The shipped web shells are KHR_mesh_quantization + EXT_meshopt_compression
// (gltfpack), which Python cannot read without a meshopt decoder. This script
// decodes them with three's GLTFLoader + MeshoptDecoder, BAKES each part's rig
// rotation (real-parts.json rotateY — so the service does catalog-socket math
// only, exactly like the compositor), flattens the node hierarchy into world
// space (the 0.15 trap: quantized int16 attributes carry a dequantize node
// transform — convert to Float32 BEFORE applying matrices), and writes a
// minimal single-primitive GLB per part to geometry-service/assets/shells/.
//
// IP: inputs are the GATED shells (exterior-only, decimated, hash-bound by
// src/lib/webModels.test.ts) — this is a lossless re-encoding of already-
// approved geometry, never a path around the gate. The output directory is
// COMMITTED so the deployed service has them; export-service-shells.json
// records the source shas so staleness is detectable.
//
// Determinism: pure re-encoding, no wall clock.

import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import * as THREE from 'three'
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js'
import { MeshoptDecoder } from 'three/examples/jsm/libs/meshopt_decoder.module.js'

const __dirname = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(__dirname, '../..')
const PUBLIC_DIR = resolve(REPO_ROOT, 'public')
const REGISTRY_PATH = resolve(PUBLIC_DIR, 'renders/web-glb-manifest.json')
const REALPARTS_PATH = resolve(REPO_ROOT, 'scripts/render-rig/real-parts.json')
const OUT_DIR = resolve(REPO_ROOT, 'geometry-service/assets/shells')
const INDEX_PATH = resolve(OUT_DIR, 'index.json')

function sha256(buf) {
  return createHash('sha256').update(buf).digest('hex')
}

/** Minimal single-primitive GLB writer: float32 positions + uint32 indices. */
function writePlainGlb(positions, indices) {
  const posBytes = Buffer.from(positions.buffer, positions.byteOffset, positions.byteLength)
  const idxBytes = Buffer.from(indices.buffer, indices.byteOffset, indices.byteLength)
  const pad = (n) => (4 - (n % 4)) % 4
  const posPad = pad(posBytes.length)
  const idxPad = pad(idxBytes.length)
  const binLen = posBytes.length + posPad + idxBytes.length + idxPad

  const mins = [Infinity, Infinity, Infinity]
  const maxs = [-Infinity, -Infinity, -Infinity]
  for (let i = 0; i < positions.length; i += 3) {
    for (let c = 0; c < 3; c++) {
      const v = positions[i + c]
      if (v < mins[c]) mins[c] = v
      if (v > maxs[c]) maxs[c] = v
    }
  }

  const json = {
    asset: { version: '2.0', generator: 'export-service-shells' },
    scene: 0,
    scenes: [{ nodes: [0] }],
    nodes: [{ mesh: 0 }],
    meshes: [{ primitives: [{ attributes: { POSITION: 0 }, indices: 1, material: 0 }] }],
    materials: [{ name: 'will-body' }],
    accessors: [
      { bufferView: 0, componentType: 5126, count: positions.length / 3, type: 'VEC3', min: mins, max: maxs },
      { bufferView: 1, componentType: 5125, count: indices.length, type: 'SCALAR' },
    ],
    bufferViews: [
      { buffer: 0, byteOffset: 0, byteLength: posBytes.length },
      { buffer: 0, byteOffset: posBytes.length + posPad, byteLength: idxBytes.length },
    ],
    buffers: [{ byteLength: binLen }],
  }
  let jsonBuf = Buffer.from(JSON.stringify(json))
  const jsonPad = pad(jsonBuf.length)
  jsonBuf = Buffer.concat([jsonBuf, Buffer.alloc(jsonPad, 0x20)])
  const bin = Buffer.concat([posBytes, Buffer.alloc(posPad), idxBytes, Buffer.alloc(idxPad)])
  const total = 12 + 8 + jsonBuf.length + 8 + bin.length
  const head = Buffer.alloc(12 + 8)
  head.writeUInt32LE(0x46546c67, 0) // glTF
  head.writeUInt32LE(2, 4)
  head.writeUInt32LE(total, 8)
  head.writeUInt32LE(jsonBuf.length, 12)
  head.writeUInt32LE(0x4e4f534a, 16) // JSON
  const binHead = Buffer.alloc(8)
  binHead.writeUInt32LE(bin.length, 0)
  binHead.writeUInt32LE(0x004e4942, 4) // BIN
  return Buffer.concat([head, jsonBuf, binHead, bin])
}

async function main() {
  const registry = JSON.parse(await readFile(REGISTRY_PATH, 'utf-8'))
  const realParts = JSON.parse(await readFile(REALPARTS_PATH, 'utf-8'))
  await mkdir(OUT_DIR, { recursive: true })

  const loader = new GLTFLoader()
  loader.setMeshoptDecoder(MeshoptDecoder)

  const index = { note: 'GENERATED by scripts/web-glb/export-service-shells.mjs from the gated web shells. Plain float32 GLBs, rig rotateY BAKED. Do not hand-edit.', shells: {} }

  for (const [partId, entry] of Object.entries(registry.models)) {
    const srcPath = resolve(PUBLIC_DIR, entry.file)
    const src = await readFile(srcPath)
    if (sha256(src) !== entry.sha256) {
      throw new Error(`${partId}: shell on disk does not match the gated registry hash`)
    }
    const gltf = await loader.parseAsync(src.buffer.slice(src.byteOffset, src.byteOffset + src.byteLength), '')

    const rigEntry = realParts[partId]
    const rotateYDeg = typeof rigEntry === 'object' ? (rigEntry.rotateY ?? 0) : 0
    const rot = new THREE.Matrix4().makeRotationY((rotateYDeg * Math.PI) / 180)

    const positions = []
    const indices = []
    gltf.scene.updateWorldMatrix(true, true)
    gltf.scene.traverse((obj) => {
      if (!obj.isMesh) return
      const geo = obj.geometry
      const posAttr = geo.attributes.position
      const world = new THREE.Matrix4().multiplyMatrices(rot, obj.matrixWorld)
      const base = positions.length / 3
      const v = new THREE.Vector3()
      for (let i = 0; i < posAttr.count; i++) {
        // .fromBufferAttribute respects `normalized` int16 (the 0.15 trap):
        // it yields the DEQUANTIZED local value; matrixWorld carries the rest.
        v.fromBufferAttribute(posAttr, i).applyMatrix4(world)
        positions.push(v.x, v.y, v.z)
      }
      const idx = geo.index
      if (idx) {
        for (let i = 0; i < idx.count; i++) indices.push(base + idx.getX(i))
      } else {
        for (let i = 0; i < posAttr.count; i++) indices.push(base + i)
      }
    })

    const out = writePlainGlb(new Float32Array(positions), new Uint32Array(indices))
    const outPath = resolve(OUT_DIR, `${partId}.glb`)
    await writeFile(outPath, out)
    index.shells[partId] = {
      file: `assets/shells/${partId}.glb`,
      bytes: out.length,
      sha256: sha256(out),
      sourceSha256: entry.sha256,
      rotateYDegBaked: rotateYDeg,
      triangles: indices.length / 3,
    }
    console.log(`  ${partId}: ${(out.length / 1024).toFixed(0)} KB, ${indices.length / 3} tris, rotY ${rotateYDeg}`)
  }

  const sorted = { ...index, shells: Object.fromEntries(Object.entries(index.shells).sort()) }
  await writeFile(INDEX_PATH, JSON.stringify(sorted, null, 2) + '\n')
  console.log(`\nwrote ${Object.keys(index.shells).length} service shells + index.json`)
}

await main()
